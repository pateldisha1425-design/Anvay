export function getVocabularyItemById(id: string): MarathiVocabularyItem | undefined {
  return MARATHI_VOCABULARY.find(item => item.id === id);
}

export function searchMarathiVocabulary(query: string): MarathiVocabularyItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return MARATHI_VOCABULARY;

  return MARATHI_VOCABULARY.filter(item => 
    item.englishEquivalent.toLowerCase().includes(q) ||
    item.marathiWord.includes(q) ||
    item.transliteration.toLowerCase().includes(q) ||
    item.scientificDomain.toLowerCase().includes(q) ||
    item.definition.toLowerCase().includes(q)
  );
}

export function getVocabularyByDomain(domain: string): MarathiVocabularyItem[] {
  if (domain === 'all') return MARATHI_VOCABULARY;
  return MARATHI_VOCABULARY.filter(item => item.scientificDomain === domain);
}
